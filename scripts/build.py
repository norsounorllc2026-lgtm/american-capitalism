#!/usr/bin/env python3
"""Bundle data/*.json and embed it inside index.html.

Writes:
  data/bundle.json        - everything in one file (for CONFIG.dataUrl)
  index.html              - updated in place between the DATA:BEGIN / DATA:END markers
  dist/wix-embed.html     - a copy you can paste straight into a Wix "Embed HTML" box
"""
import json, re, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
PARTS = ["people", "wealth", "business", "articles", "resources", "meta"]


def main():
    bundle = {}
    for p in PARTS:
        f = DATA / f"{p}.json"
        bundle[p] = json.loads(f.read_text(encoding="utf-8")) if f.exists() else {}
    (DATA / "bundle.json").write_text(json.dumps(bundle, ensure_ascii=False), encoding="utf-8")

    page = (ROOT / "index.html").read_text(encoding="utf-8")
    payload = json.dumps(bundle, ensure_ascii=False).replace("</", "<\\/")  # safe inside <script>
    block = ('<!-- DATA:BEGIN (generated by scripts/build.py — do not edit by hand) -->\n'
             f'<script type="application/json" id="data-bundle">{payload}</script>\n<!-- DATA:END -->')
    page, n = re.subn(r"<!-- DATA:BEGIN.*?<!-- DATA:END -->", lambda m: block, page, flags=re.S)
    if n != 1:
        raise SystemExit("DATA markers not found in index.html")
    (ROOT / "index.html").write_text(page, encoding="utf-8")

    dist = ROOT / "dist"
    dist.mkdir(exist_ok=True)
    (dist / "wix-embed.html").write_text(page, encoding="utf-8")
    print(f"Embedded {len(payload):,} bytes of data; people={len(bundle['people'].get('people', []))}, "
          f"articles={len(bundle['articles'].get('items', []))}")


if __name__ == "__main__":
    main()
